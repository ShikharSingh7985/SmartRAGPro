"""Generate release tables/charts exclusively from recorded measurements."""

import json
import os
import statistics
import xml.etree.ElementTree as ET
from datetime import UTC, datetime
from pathlib import Path

os.environ.setdefault("MPLCONFIGDIR", str(Path("evaluation/.cache/matplotlib").resolve()))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
matplotlib.rcParams["svg.hashsalt"] = "smartrag-release-v1"
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path("evaluation/release")
DOCS = Path("docs/benchmarks")


def read(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def test_result(path: Path):
    if not path.exists():
        return {"status": "NOT VERIFIED", "source": str(path)}
    suite = ET.parse(path).getroot().find("testsuite")
    counts = {
        key: int(suite.attrib.get(key, 0)) for key in ["tests", "failures", "errors", "skipped"]
    }
    return {
        **counts,
        "passed": counts["tests"] - counts["failures"] - counts["errors"] - counts["skipped"],
        "seconds": float(suite.attrib["time"]),
    }


def main() -> None:
    ROOT.mkdir(parents=True, exist_ok=True)
    DOCS.mkdir(parents=True, exist_ok=True)
    retrieval = read(Path("evaluation/results/retrieval.json"))
    quality = read(Path("evaluation/results/analysis.json"))
    selected = {"tfidf", "bm25", "dense", "rrf_0.5", "rrf_0.5_rerank"}
    heldout = [
        r for r in retrieval["aggregates"] if r["split"] == "test" and r["variant"] in selected
    ]
    load = [read(path) for path in sorted((ROOT / "load").glob("users-*.json"))]
    load.sort(key=lambda row: row["concurrency"])
    acceptance = read(ROOT / "user-acceptance.json")
    ingestion = (
        [o for o in acceptance["observations"] if o["stage"] == "ingestion"] if acceptance else []
    )
    questions = (
        [o for o in acceptance["observations"] if o["stage"] == "question"] if acceptance else []
    )
    report = {
        "generated_at": datetime.now(UTC).isoformat(),
        "native_tests": test_result(ROOT / "native-final.xml"),
        "service_tests": test_result(ROOT / "service-final.xml"),
        "load_tests": test_result(ROOT / "load-tests.xml"),
        "runtime": acceptance["runtime"] if acceptance else None,
        "retrieval": {
            "scope": (
                "historical real Google embeddings, cached; synthetic unreviewed page-chunk labels"
            ),
            "corpus": retrieval["corpus"],
            "embedding": {
                k: retrieval["embedding"][k]
                for k in ["provider", "model", "dimensions", "index_version"]
            },
            "heldout": heldout,
        },
        "historical_answer_proxies": quality["answer_proxies"],
        "historical_token_usage": quality["tokens"],
        "historical_vectorizer_memory": quality["memory"],
        "live_acceptance": {"ingestion": ingestion, "questions": questions},
        "load": load,
        "monitoring": read(ROOT / "monitoring.json"),
        "restore": read(ROOT / "restore.json"),
        "conversation_restart": read(ROOT / "conversations.json"),
        "security_acceptance": read(ROOT / "security-acceptance.json"),
        "unavailable": [
            "Independent human semantic correctness/faithfulness assessment",
            "Production network throughput and live-model concurrent load",
            "Time to first streamed token (no token streaming)",
            "Current acceptance per-call billing costs and provider-throttle load",
            "Hosted Langfuse delivery, public cloud/TLS deployment",
            "S3/Qdrant off-host restore and production RPO/RTO",
        ],
    }
    (ROOT / "summary.json").write_text(json.dumps(report, indent=2) + "\n")
    lines = [
        "# Final engineering measurements",
        "",
        "Generated by `uv run python -m evaluation.release_report` from committed public",
        "synthetic measurements. Missing measurements are unavailable, never zero.",
        "",
        "## Validation",
        "",
        "| Run | Passed | Failed/errors | Skipped | Seconds |",
        "|---|---:|---:|---:|---:|",
    ]
    for label, key in [
        ("Native", "native_tests"),
        ("Real disposable services", "service_tests"),
        ("Isolated load", "load_tests"),
    ]:
        result = report[key]
        if "passed" in result:
            lines.append(
                f"| {label} | {result['passed']} | {result['failures'] + result['errors']} "
                f"| {result['skipped']} | {result['seconds']:.2f} |"
            )
        else:
            lines.append(f"| {label} | NOT VERIFIED | — | — | — |")
    lines += [
        "",
        "## Retrieval comparison (historical Phase 4 evidence)",
        "",
        "Ten synthetic source books, 60 authored page-chunks and 108 labeled queries.",
        "The comparable held-out configurations below use 53 answerable questions.",
        "Google `models/gemini-embedding-001`, 768 dimensions, index v1; cached real",
        "embeddings are reused, so these are not new provider latency measurements.",
        "Relevance is authored page-chunk membership. Recall@K is known relevant items",
        "retrieved divided by all known relevant items; precision divides by K; hit rate",
        "is any relevant hit. MRR uses first relevant rank; nDCG discounts ranked relevance.",
        "These labels are synthetic and unreviewed. Validation selected dense; reranking",
        "regressed. There is no comparable original production baseline or accuracy claim.",
        "",
        "| Configuration | n | Recall@1 | Recall@3 | Recall@5 | Recall@10 "
        "| Precision@5 | Hit@5 | MRR | nDCG@5 |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in heldout:
        values = " | ".join(
            f"{r[k]:.4f}"
            for k in [
                "recall@1",
                "recall@3",
                "recall@5",
                "recall@10",
                "precision@5",
                "hit_rate@5",
                "mrr",
                "ndcg@5",
            ]
        )
        lines.append(f"| {r['variant']} | {r['n']} | {values} |")
    lines += [
        "",
        "RRF .5 means equal lexical/dense reciprocal-rank shares, not raw-score averaging.",
        "The optional reranker uses bounded term/bigram coverage and prior rank, not a",
        "neural cross-encoder. Full metrics, bootstrap intervals, ablations and failures",
        "remain in `evaluation/results/retrieval.json` and the earlier comparison report.",
        "",
        "## Live provider acceptance",
        "",
        "Real HTTP, PostgreSQL, worker, S3, Redis, Qdrant and Gemini; public generated PDFs.",
        "Ingestion times include polling/queue wait and first-use effects; no cold/warm",
        "classification is inferred from filename/order. Small samples do not support",
        "reliable p95/p99. Figure checks verify OCR-visible labels, not advanced vision.",
        "",
        "| Synthetic source | Pages | Chunks | Tables | Figures | Upload-to-ready seconds |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for row in ingestion:
        lines.append(
            f"| {row['source']} | {row['pages']} | {row['chunks']} | {row['tables']} "
            f"| {row['figures']} | {row['seconds']:.3f} |"
        )
    if ingestion:
        lines += [
            "",
            f"Acceptance corpus: {len(ingestion)} public synthetic uploads, "
            f"{sum(r['pages'] for r in ingestion)} pages and "
            f"{sum(r['chunks'] for r in ingestion)} published chunks. "
            "Quarantined content is excluded from published chunk counts.",
        ]
    if questions:
        seconds = [q["seconds"] for q in questions]
        lines += [
            "",
            f"{len(questions)} live answer checks: {sum(q['passed'] for q in questions)} passed.",
            f"Mean HTTP whole-turn latency {statistics.mean(seconds):.3f} s; "
            f"median {statistics.median(seconds):.3f} s.",
            "Question/word/citation assertions are reproducible proxies, not independently",
            "reviewed semantic correctness. Full source-page attribution is in the JSON.",
        ]
    lines += [
        "",
        "## Concurrent infrastructure experiment",
        "",
        "Real disposable services, in-process ASGI clients, isolated 30 ms simulated",
        "generator and 8-dimensional test embeddings. Four sequential turns per user.",
        "No Gemini load, internet ingress, OCR concurrency or production capacity claim.",
        "RSS/CPU refer to the test/API process, not total infrastructure. SQL test pool",
        "uses SQLAlchemy defaults (5 plus 10 overflow); runtime defaults are 5 plus 5.",
        "p95 is omitted below 20 samples and p99 below 100; single-run tails remain noisy.",
        "",
        "| Concurrent users | Requests | Failures | Requests/s | p50 s | p95 s "
        "| p99 s | Peak RSS MiB | CPU s |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in load:
        p95 = f"{r['p95_seconds']:.3f}" if r["p95_seconds"] is not None else "unavailable"
        p99 = f"{r['p99_seconds']:.3f}" if r["p99_seconds"] is not None else "unavailable"
        lines.append(
            f"| {r['concurrency']} | {r['requests']} | {r['failures']} "
            f"| {r['throughput_rps']:.2f} | {r['p50_seconds']:.3f} | {p95} | {p99} "
            f"| {r['peak_process_rss_bytes'] / 1048576:.2f} | {r['cpu_seconds']:.2f} |"
        )
    if load:
        hardware = load[-1]["hardware"]
        lines += [
            "",
            f"Container-visible hardware: {hardware['logical_cpu']} logical CPUs, "
            f"{hardware['ram_bytes'] / 1073741824:.2f} GiB RAM, "
            f"{hardware['os']} {hardware['machine']} (Docker Desktop).",
        ]
        fig, axes = plt.subplots(1, 2, figsize=(9, 3.5))
        axes[0].plot([r["concurrency"] for r in load], [r["p50_seconds"] for r in load], "o-")
        axes[0].set(xlabel="Concurrent synthetic users", ylabel="Median HTTP seconds")
        axes[1].plot(
            [r["concurrency"] for r in load],
            [r["peak_process_rss_bytes"] / 1048576 for r in load],
            "o-",
        )
        axes[1].set(xlabel="Concurrent synthetic users", ylabel="Test/API process peak RSS MiB")
        fig.suptitle("Isolated providers + real services; single local runs")
        fig.tight_layout()
        fig.savefig(DOCS / "release-load.svg", metadata={"Date": None})
        chart = DOCS / "release-load.svg"
        chart.write_text("\n".join(line.rstrip() for line in chart.read_text().splitlines()) + "\n")
        plt.close(fig)
        lines += ["", "![Measured synthetic load](release-load.svg)"]
    lines += [
        "",
        "## Answer quality, security and remaining measurements",
        "",
        "Historical Gemini answer evidence contains 24 calls and provider-reported token",
        f"usage of {quality['tokens']['total_tokens']} total tokens. The earlier quality report",
        "records phrase, context and citation proxies separately. Those measurements",
        "do not establish human correctness or faithfulness. The current acceptance",
        "run's per-call billing cost is unavailable; monitoring collects reported tokens",
        "but no model price is invented. TTFT is unavailable because answers are not streamed.",
        "",
        "The earlier isolated vectorizer experiment measured mean peak RSS of "
        f"{quality['memory']['tfidf']['peak_rss_mib_mean']:.2f} MiB (TF-IDF) and "
        f"{quality['memory']['hashing']['peak_rss_mib_mean']:.2f} MiB (hashing). "
        "This is not total application RSS or a production memory improvement.",
        "",
        "See `evaluation/security/policy-results.json` for deterministic adversarial cases,",
        "the security reports for historical live failures, and `evaluation/release/` for",
        "current live acceptance, monitoring, restart and PostgreSQL restore evidence.",
        "No universal prompt-injection immunity or production disaster-recovery claim is made.",
        "",
        "Unavailable: human-reviewed semantic evaluation, real-provider concurrent load,",
        "hosted Langfuse delivery, public TLS/cloud endpoint, full object/vector restore,",
        "production RPO/RTO, provider billing/cost calibration and target-host capacity.",
    ]
    snapshot = (report["monitoring"] or {}).get("metrics_snapshot", {})
    if snapshot:
        lines += [
            "",
            "## Operational metrics snapshot",
            "",
            "Prometheus counters since the latest API process start, not an isolated",
            "billing ledger or peak-memory measurement. Missing values remain unavailable.",
            "",
            "| Metric | Measured value |",
            "|---|---:|",
            *[
                f"| {name} | {value if value is not None else 'unavailable'} |"
                for name, value in snapshot.items()
            ],
        ]
    conversation = report["conversation_restart"]
    if conversation:
        lines += [
            "",
            "## Persistent conversational acceptance",
            "",
            f"Recorded result: **{conversation['status']}**. "
            f"Actual API restart requested: {conversation.get('api_restart_requested', False)}.",
            "The strengthened check verifies the fourth answer's method identity against",
            "the preceding answer's order, as well as citation ownership/page. The current",
            "run correctly explains early stopping and states that no example is supplied",
            "by the fixture. Earlier citation-only checks missed a stale ordinal list;",
            "that failed semantic review and subsequent label-extraction failure are preserved.",
            "Numbered lists, prose and descriptive labels now have deterministic regressions.",
            "",
            "| Turn | HTTP whole-turn seconds | Cited pages |",
            "|---|---:|---|",
            *[
                f"| {o['turn']} | {o['seconds']:.3f} | {o['source_pages']} |"
                for o in conversation["observations"]
                if o["stage"] == "whole_turn"
            ],
            "",
            "Each live artifact records its candidate snapshot. The general 14-check",
            "acceptance preceded the ordinal-memory correction; this dedicated four-turn",
            "test ran against the corrected source fingerprint. Full deterministic and",
            "real-service regressions cover the remaining integration paths.",
        ]
    (DOCS / "final-report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Generated public release summary and measured report/chart")


if __name__ == "__main__":
    main()
